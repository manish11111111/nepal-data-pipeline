"""Dataset summary page. Designed and built by Manish Chapagain."""

from pathlib import Path

import pandas as pd
import plotly.express as px
import streamlit as st

from src.ui import (
    apply_theme,
    chart_layout,
    footer,
    page_header,
    sidebar_brand,
    sidebar_footer,
    sidebar_status,
)


PROJECT_ROOT = Path(__file__).resolve().parent.parent
CLEAN_PATH = PROJECT_ROOT / "data" / "processed" / "observations_clean.parquet"
DATASET_SUMMARY_PATH = PROJECT_ROOT / "data" / "processed" / "dataset_summary.csv"

st.set_page_config(page_title="Dataset · Nepal Pipeline", page_icon="📈", layout="wide")
apply_theme()


@st.cache_data
def load_clean():
    return pd.read_parquet(CLEAN_PATH)


@st.cache_data
def load_summary():
    return pd.read_csv(DATASET_SUMMARY_PATH)


sidebar_brand()
sidebar_status(
    [
        ("Cleaned dataset", CLEAN_PATH),
        ("Dataset summary", DATASET_SUMMARY_PATH),
    ]
)
sidebar_footer()

page_header(
    "Overview · Dataset",
    "Dataset summary",
    "Dataset-level aggregates generated by the pipeline.",
)

if not CLEAN_PATH.exists():
    st.error("Cleaned dataset not found. Run `python -m src.pipeline`.")
    st.stop()

df = load_clean()

if DATASET_SUMMARY_PATH.exists():
    st.dataframe(load_summary(), use_container_width=True, hide_index=True)
else:
    st.warning("dataset_summary.csv not found.")

st.markdown('<div class="section-rule"></div>', unsafe_allow_html=True)

col1, col2 = st.columns(2)

with col1:
    st.subheader("Observations by dataset")
    counts = df["dataset_id"].value_counts().reset_index()
    counts.columns = ["dataset_id", "count"]
    fig = px.bar(
        counts, x="dataset_id", y="count",
        template="plotly_dark",
        color_discrete_sequence=["#6366f1"],
    )
    st.plotly_chart(chart_layout(fig), use_container_width=True)

with col2:
    st.subheader("Observations by status")
    status = df["status"].value_counts().reset_index()
    status.columns = ["status", "count"]
    fig = px.pie(
        status, names="status", values="count", hole=0.55,
        template="plotly_dark",
        color_discrete_sequence=["#6366f1", "#ec4899", "#22d3ee", "#f59e0b"],
    )
    st.plotly_chart(chart_layout(fig), use_container_width=True)

st.subheader("Observations by period type")
period = df["period_type"].value_counts().reset_index()
period.columns = ["period_type", "count"]
fig = px.bar(
    period, x="period_type", y="count",
    template="plotly_dark", color_discrete_sequence=["#22d3ee"],
)
st.plotly_chart(chart_layout(fig), use_container_width=True)

footer()